"""Drive one leg of the course headlessly, to find out which parts the robot can do.

The race is a single 33-waypoint run, which is the wrong shape for a question like "can the
robot get from waypoint 22 to waypoint 23". Answering that by running the whole race costs
several minutes and, worse, only tells you about the segment if everything before it went
right -- and the run currently stops dead at the 0.377 m step at waypoint 16, so nothing
after it has been observed at all.

This starts the robot at a chosen waypoint and drives to another one. It is deliberately the
real stack and not a model of it: the shipped ``policy.onnx``, the observation layout taken
from ``s10_rl.observation`` which is the same definition the C++ runner is generated from,
and the actual :class:`PurePursuitController` and :class:`Course` the follower node uses. A
failure here is a failure of the thing that will run in the race. A reimplementation would
only tell us about the reimplementation.

**This is test-only and off by default.** Nothing in the race launch imports it, it writes
only where it is told to, and it does not touch ``course.yaml`` -- a sub-course is built in
memory from a slice of the waypoint list, because hand-editing the generated course file
would both break ``extract_waypoints.py --check`` and silently change the scored run.

Usage::

    python3 -m s10_climb.segment_runner --start 22 --end 23 --seeds 3 --out /res/post_wp16

Seeds do not change the physics, which is deterministic. They jitter the starting pose --
position, heading and joint angles -- because the question worth answering is not "does this
work from one exact pose" but "does this work". A segment that only succeeds from a single
spawn is a segment that will fail in a real run, where the robot arrives however it arrives.
"""

